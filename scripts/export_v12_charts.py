"""Render reproducible presentation figures from genuine v12 five-policy benchmark CSV/JSON.
No generated/fabricated improvements; numbers are generated by v12.benchmark.
"""
import json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'reports/V12_FIVE_POLICY_HOLDOUT.json').read_text())
rows=data['results'];scenarios=data['scenarios']
policies=['RELAY_V10','RELAY_V11','A_CRITICAL','A_EDF'];labels=['RELAY v10','RELAY v11','RELAY + Model A','RELAY + EDF']

fig,ax=plt.subplots(figsize=(12,5.2))
x=np.arange(len(scenarios));bar=.19
for k,policy in enumerate(policies):
 y=[next(v['cost_reduction_pct'] for v in rows if v['scenario']==sc and v['policy']==policy) for sc in scenarios]
 ax.bar(x+(k-1.5)*bar,y,bar,label=labels[k]);
ax.axhline(0,color='#546575',lw=.8)
ax.set_xticks(x, ['Normal','Peak','Crew shortage','Cold outage','High capacity','Disruption'])
ax.set_ylabel('Synthetic cost reduction versus FCFS (%)')
ax.set_title('RELAY v12 | Five-way paired policy comparison — 500 episodes per scenario',loc='left',fontweight='bold')
ax.legend(ncol=4,loc='upper center',bbox_to_anchor=(.5,-.12),frameon=False,fontsize=9)
ax.grid(axis='y',alpha=.16);ax.set_axisbelow(True)
fig.subplots_adjust(bottom=.24,top=.87,left=.09,right=.99)
fig.savefig(ROOT/'reports/V12_COST_REDUCTION_BY_SCENARIO.png',dpi=200);plt.close(fig)

normal=[r for r in rows if r['scenario']=='normal'];fig,ax=plt.subplots(figsize=(8.6,6.5))
for r in normal:
 ax.scatter(r['cost_mean'],r['on_time_pct'],s=120,zorder=3)
 ax.annotate(r['label'],(r['cost_mean'],r['on_time_pct']),xytext=(7,8),textcoords='offset points',fontsize=10,weight='bold')
ax.set_xlabel('Mean synthetic cost / episode (lower is better)')
ax.set_ylabel('On-time rate, full cohort (%) (higher is better)')
ax.set_title('Cost–Quality frontier | Normal synthetic operation',loc='left',fontweight='bold')
ax.grid(alpha=.2);fig.tight_layout()
fig.savefig(ROOT/'reports/V12_COST_QUALITY_FRONTIER.png',dpi=210);plt.close(fig)

fig,axs=plt.subplots(1,2,figsize=(12,4.4));axs[0].bar([r['label'] for r in normal],[r['on_time_pct'] for r in normal]);axs[0].set_ylabel('On-time cohort rate (%)');axs[0].set_title('Service quality')
base=next(r['cv90'] for r in normal if r['policy']=='FCFS');axs[1].bar([r['label'] for r in normal],[(base-r['cv90'])/base*100 for r in normal]);axs[1].set_ylabel('Worst-decile episode cost reduction (%)');axs[1].set_title('Tail risk / CVaR90')
for ax in axs:ax.tick_params(axis='x',rotation=25);ax.grid(axis='y',alpha=.15);ax.set_axisbelow(True)
fig.suptitle('Quality and risk are different objectives',fontweight='bold');fig.tight_layout()
fig.savefig(ROOT/'reports/V12_SERVICE_AND_TAIL_RISK.png',dpi=200);plt.close(fig)
print('Generated 3 reproducible PNG charts')
