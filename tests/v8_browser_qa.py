import json,time
from pathlib import Path
from playwright.sync_api import sync_playwright
base='http://127.0.0.1:8899/'
out=Path(__file__).parent
r={}
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[]
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.goto(base,wait_until='domcontentloaded',timeout=30000)
 page.wait_for_timeout(1700)
 r['home_title']=page.title()
 r['ground_visible']=page.locator('#ground-screen').is_visible()
 r['ground_canvases']=page.locator('#ground-screen canvas').count()
 r['document_scroll_height']=page.evaluate('document.documentElement.scrollHeight')
 r['viewport_height']=900
 page.screenshot(path=str(out/'v8_ground_desktop.png'),full_page=True)
 page.locator('[data-tab="tower"]').click();page.wait_for_timeout(350)
 r['tower_visible']=page.locator('#tower-screen').is_visible()
 r['tower_event_cards']=page.locator('.event-card').count()
 page.screenshot(path=str(out/'v8_tower_desktop.png'),full_page=True)
 page.locator('[data-tab="customer"]').click();page.wait_for_timeout(500)
 r['customer_visible']=page.locator('#customer-screen').is_visible()
 r['portfolio_cards']=page.locator('.shipment-card').count()
 page.screenshot(path=str(out/'v8_customer_desktop.png'),full_page=True)
 page.locator('#newOrderBtn').click();page.wait_for_timeout(200)
 r['order_drawer_visible']=page.locator('#drawer').is_visible()
 page.locator('#orderForm select[name="destination"]').select_option('SYD')
 page.locator('#orderForm').locator('button[type="submit"]').click()
 page.wait_for_timeout(2500)
 r['order_created']=page.locator('#shipAwb').inner_text().startswith('SYN-CX-D')
 r['portfolio_after_create']=page.locator('.shipment-card').count()
 page.screenshot(path=str(out/'v8_customer_new_order.png'),full_page=True)
 page.locator('[data-tab="ground"]').click()
 page.locator('#settingsBtn').click()
 r['settings_visible']=page.locator('#settingsPop').is_visible()
 page.locator('#crew').fill('2')
 page.locator('#applySettings').click()
 page.wait_for_timeout(700)
 page.locator('#speed').select_option('100')
 page.wait_for_timeout(850)
 page.locator('#globalPlay').click()
 page.wait_for_timeout(2500)
 r['play_running']=page.locator('#liveState').inner_text()
 r['throughput']=page.locator('#achieved').inner_text()
 page.locator('#globalPlay').click()
 page.wait_for_timeout(600)
 r['pause_state']=page.locator('#liveState').inner_text()
 page.screenshot(path=str(out/'v8_ground_after_tick.png'),full_page=True)
 r['page_errors']=errors
 page.set_viewport_size({'width':1366,'height':768});page.wait_for_timeout(250)
 r['desktop_768_scroll_height']=page.evaluate('document.documentElement.scrollHeight')
 page.screenshot(path=str(out/'v8_ground_1366.png'),full_page=True)
 page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(200)
 r['mobile_doc_height']=page.evaluate('document.documentElement.scrollHeight')
 page.screenshot(path=str(out/'v8_ground_mobile.png'),full_page=True)
 browser.close()
(out/'V8_BROWSER_QA.json').write_text(json.dumps(r,indent=2))
print(json.dumps(r,indent=2))
